#!/usr/bin/env node
// Inline the critical part of the four shared style sheets into index.html and defer the rest, the way the
// Angular build does with Beasties: the four sheets are concatenated into public/styles.css, the rules whose
// selectors match the static document (:root tokens, html, body, universal reset) land in a <style>, the file
// keeps only the other rules (pruned, minified) and stays linked with media="print" swapped to "all" once
// loaded, so the first paint waits for no style sheet and a second visit reads the file from the browser cache.
// usage: node critical-css.mjs   (idempotent: regenerates the block between the two critical-css markers)
import Beasties from 'beasties'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT   = dirname(fileURLToPath(import.meta.url))
const FILE   = join(ROOT, 'index.html')
const SHEET  = 'public/styles.css'
const SHEETS = ['design-system', 'variables', 'base', 'components']
const OPEN   = /<!-- critical-css:[^]*?-->/
const CLOSE  = '<!-- /critical-css -->'
const NOTE   = '<!-- critical-css: generated by `node critical-css.mjs` from public/styles/*.css (Beasties, as the Angular build does), do not edit by hand -->'
// the app must not paint before its deferred sheet is active: on a fast network the module script wins the race
// against the media swap and Lighthouse records an unstyled frame (layout shift 0.2-0.3, score -6 to -8)
const SHIELD = 'html:has(link[media=print]) mjs-weather-app{visibility:hidden}'

writeFileSync(join(ROOT, SHEET), SHEETS.map(s => readFileSync(join(ROOT, 'public/styles', s + '.css'), 'utf8')).join('\n'))
const html   = readFileSync(FILE, 'utf8')
const open   = html.match(OPEN), close = html.indexOf(CLOSE)
if(!open || close < 0) throw new Error('index.html: critical-css markers not found')
const source = html.slice(0, open.index) + NOTE + `\n  <link rel="stylesheet" href="${SHEET}">\n  ` + html.slice(close)

// Beasties writes the pruned sheet without awaiting it: keep the promise to report its final size
class Pruner extends Beasties { writeFile(file, data) { return this.pending = super.writeFile(file, data) } }
const beasties = new Pruner({ path: ROOT, publicPath: '', preload: 'media', pruneSource: true, logLevel: 'warn' })
const out      = (await beasties.process(source)).replace('</style>', SHIELD + '</style>')
await beasties.pending
writeFileSync(FILE, out)
const inlined  = (out.match(/<style>[^]*?<\/style>/) || [''])[0].length
console.log(`index.html: ${Buffer.byteLength(out)} bytes (critical CSS inlined: ${inlined}), ${SHEET}: ${readFileSync(join(ROOT, SHEET)).length} bytes deferred`)
